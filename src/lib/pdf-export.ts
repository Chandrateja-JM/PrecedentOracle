import { jsPDF } from "jspdf";

interface Row { n: number; text: string; status: string; confidence: number; source: string }

export function exportCitationReport(rows: Row[], score: number) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const margin = 48;
  let y = margin;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text("PrecedentOracle — Citation Verification Report", margin, y);
  y += 24;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.setTextColor(120);
  doc.text(`Overall verification: ${score}%  ·  ${rows.length} citations  ·  Generated ${new Date().toLocaleDateString()}`, margin, y);
  y += 24;
  doc.setTextColor(0);
  doc.setDrawColor(220);
  doc.line(margin, y, 595 - margin, y);
  y += 18;

  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.text("#", margin, y);
  doc.text("Citation", margin + 24, y);
  doc.text("Status", margin + 340, y);
  doc.text("Conf.", margin + 430, y);
  y += 14;
  doc.line(margin, y, 595 - margin, y);
  y += 14;
  doc.setFont("helvetica", "normal");

  for (const r of rows) {
    if (y > 780) { doc.addPage(); y = margin; }
    const lines = doc.splitTextToSize(r.text, 300);
    doc.text(String(r.n), margin, y);
    doc.text(lines, margin + 24, y);
    doc.text(r.status, margin + 340, y);
    doc.text(`${r.confidence}%`, margin + 430, y);
    y += Math.max(14, lines.length * 12) + 6;
  }

  y += 12;
  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text("Generated by PrecedentOracle · Every citation verified against Indian Kanoon · Not legal advice.", margin, 820);
  doc.save(`citation-report-${Date.now()}.pdf`);
}

export function exportTextReport(opts: { title: string; subtitle: string; sections: { title: string; body: string }[] }) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const margin = 48;
  let y = margin;

  doc.setFont("times", "bold");
  doc.setFontSize(20);
  doc.text(opts.title, margin, y);
  y += 22;
  doc.setFont("times", "italic");
  doc.setFontSize(12);
  doc.setTextColor(110);
  doc.text(opts.subtitle, margin, y);
  y += 22;
  doc.setTextColor(0);

  for (const s of opts.sections) {
    if (y > 760) { doc.addPage(); y = margin; }
    doc.setFont("helvetica", "bold");
    doc.setFontSize(13);
    doc.text(s.title, margin, y);
    y += 16;
    doc.setFont("times", "normal");
    doc.setFontSize(11);
    const lines = doc.splitTextToSize(s.body, 500);
    for (const line of lines) {
      if (y > 800) { doc.addPage(); y = margin; }
      doc.text(line, margin, y);
      y += 14;
    }
    y += 10;
  }

  doc.save(`${opts.title.toLowerCase().replace(/\s+/g, "-")}-${Date.now()}.pdf`);
}

// Bare Act → PDF styled like a legal textbook.
export function exportBareActPdf(opts: {
  shortName: string;
  fullName: string;
  year: number;
  sections: { number: string; title: string; text: string }[];
}) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const margin = 56;
  const width = 595 - margin * 2;
  let y = margin;

  // Cover
  doc.setFillColor(245, 241, 232);
  doc.rect(0, 0, 595, 842, "F");
  doc.setTextColor(40, 30, 18);
  doc.setFont("times", "bold");
  doc.setFontSize(28);
  const titleLines = doc.splitTextToSize(opts.fullName, width);
  doc.text(titleLines, 297.5, 280, { align: "center" });
  doc.setFontSize(14);
  doc.setFont("times", "italic");
  doc.text(`${opts.shortName} · ${opts.year}`, 297.5, 330, { align: "center" });
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(120, 90, 30);
  doc.text("PrecedentOracle · Bare Acts Library", 297.5, 760, { align: "center" });

  for (const s of opts.sections) {
    doc.addPage();
    doc.setFillColor(245, 241, 232);
    doc.rect(0, 0, 595, 842, "F");
    y = margin;
    doc.setTextColor(150, 110, 30);
    doc.setFont("times", "bold");
    doc.setFontSize(28);
    doc.text(s.number, margin, y + 8);
    y += 32;
    doc.setTextColor(40, 30, 18);
    doc.setFont("times", "bold");
    doc.setFontSize(14);
    const tLines = doc.splitTextToSize(s.title, width);
    doc.text(tLines, margin, y);
    y += tLines.length * 16 + 10;
    doc.setDrawColor(200, 170, 90);
    doc.line(margin, y, margin + width, y);
    y += 18;
    doc.setFont("times", "normal");
    doc.setFontSize(11.5);
    const bodyLines = doc.splitTextToSize(s.text, width);
    for (const line of bodyLines) {
      if (y > 780) { doc.addPage(); doc.setFillColor(245, 241, 232); doc.rect(0, 0, 595, 842, "F"); y = margin; }
      doc.text(line, margin, y);
      y += 16;
    }
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(120);
    doc.text(`${opts.shortName} · ${s.number}`, 297.5, 810, { align: "center" });
  }

  doc.save(`${opts.shortName.toLowerCase().replace(/\s+/g, "-")}-${Date.now()}.pdf`);
}

// Procedural checklist → printable PDF with checkboxes.
export function exportChecklistPdf(opts: {
  caseTitle: string;
  court: string;
  caseType: string;
  stages: { title: string; duration: string; statute: string; checklist: string[] }[];
}) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const margin = 48;
  let y = margin;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Procedural Checklist", margin, y);
  y += 22;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.setTextColor(110);
  doc.text(`${opts.caseTitle} · ${opts.court} · ${opts.caseType}`, margin, y);
  y += 20;
  doc.setTextColor(0);

  for (const s of opts.stages) {
    if (y > 760) { doc.addPage(); y = margin; }
    doc.setFont("helvetica", "bold");
    doc.setFontSize(13);
    doc.text(`${s.title} — ${s.duration}`, margin, y);
    y += 14;
    doc.setFont("helvetica", "italic");
    doc.setFontSize(9.5);
    doc.setTextColor(110);
    doc.text(s.statute, margin, y);
    y += 14;
    doc.setTextColor(0);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);
    for (const item of s.checklist) {
      if (y > 790) { doc.addPage(); y = margin; }
      doc.rect(margin, y - 9, 11, 11);
      const lines = doc.splitTextToSize(item, 470);
      doc.text(lines, margin + 18, y);
      y += Math.max(14, lines.length * 13) + 4;
    }
    y += 8;
  }
  doc.save(`checklist-${Date.now()}.pdf`);
}

// BibTeX export for Indian case citations.
export function exportBibTeX(entries: { key: string; case: string; year: number; reporter: string; court: string }[]) {
  const lines: string[] = [];
  for (const e of entries) {
    lines.push(`@case{${e.key},`);
    lines.push(`  title  = {${e.case}},`);
    lines.push(`  year   = {${e.year}},`);
    lines.push(`  journal = {${e.reporter}},`);
    lines.push(`  institution = {${e.court}}`);
    lines.push(`}`);
    lines.push("");
  }
  const blob = new Blob([lines.join("\n")], { type: "application/x-bibtex" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url; a.download = `citations-${Date.now()}.bib`;
  document.body.appendChild(a); a.click(); a.remove();
  URL.revokeObjectURL(url);
}
